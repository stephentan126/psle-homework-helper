r"""
Bootstrap a hint review queue for QLoRA training. The output is a queue for human review, not a
finished training set.

Approach (Issue 246, hybrid): candidate hints are generated by the live gate and `generate_hint()`
pipeline over the filtered candidate pool, but every candidate must go through a full human review
(review_hint_queue.py or confirm_hint_prescreen.py) before it can be a training target. The
reviewed text is what trains, never the raw bootstrap output. This script only builds the queue:
it trains nothing and does not write to `psle.db`.

Candidate pool: Issue 246's structural exclusion chain, re-run fresh, plus two filters added after
the integrity check:
    0. all rows
    1. exclude superseded_by IS NOT NULL          (dedup losers, Issues 231, 290)
    2. exclude extraction_flag ~ non_question_boilerplate
    3. require worked_solution_text               (the form-transfer signal for QLoRA, Issue 246)
    4. require answer_value                       [new: 1,827 rows had no answer]
    5. exclude extraction_flag ~ answer_key_verification_pending OR no_matching_answer_key_row
                                                  [new: quarantine and provenance-gap flags]
Rows with `has_diagram = 1` are kept (Issue 246 proposed excluding them but left it open). They
are counted separately and carry `has_diagram` in every record, so review can decide per row.

Answer-value screen: each candidate's `answer_value` is classified with the same buckets as the
integrity check's CHECK 3b. Rows whose `answer_value` looks like raw OCR'd working rather than a
final answer (`400-168=232cm2`, multi-line step dumps and so on) are excluded by default. The gate
would mostly cap them at Tier 1 anyway, and a hint grounded in a garbled answer key has little
value. Their ids are printed and written to a `*.skipped_suspect_answers.json` sidecar.
`--include-suspect-answers` keeps them.

Answer-value normalisation (`normalize_answer_value()`) applies only to the gate call in this
script; it changes neither `gate.py` nor `psle.db`. It was added because, at the time:
  `gate._values_equal('36', '$36')`  -> False  (a leading '$' was not covered by
      `gate._UNIT_SUFFIX_RE`, which only strips a trailing unit suffix)
  `gate._values_equal('64', '64°')`  -> False  ('°' was not in `_UNIT_SUFFIX_RE`)
In the 1,205-row pool, 141 rows had a leading '$', 145 a trailing '°' and 11 a Unicode '²' or '³'
(`cm²` did not match the ASCII `cm2`). Together, about 25% of the pool would have failed to match
even a correct model answer and been capped at Tier 1 for reasons unrelated to the model.
Issue 293 has since fixed these gaps in `gate.strip_units()` itself. `normalize_answer_value()` is
still kept separate on purpose:
  (1) `gate.strip_units()` also strips plain unit suffixes (`cm`, `kg`, `%`, `min`, ...) that this
      function never touched. That is harmless for the gate, which re-strips its input anyway,
      but delegating would change what this script reports as "normalised" beyond the three
      shapes measured and published (287 of 1,205 in Issue 292).
  (2) `gate.strip_units()` has no multi-line guard (it does not need one, since
      `run_full_gate_pipeline()` rejects non-numeric compound content on other grounds). The
      explicit multi-line bail-out here keeps the published count reproducible.
For the three shapes both cover, the gate outcomes are numerically equivalent, so the duplication
is for stable reporting, not a correctness gap.

Normalisation produces an `answer_value_gate` string used only in the `run_full_gate_pipeline()`
call (the comparison, and the numeric-parse check in `classify_question_type()`). The original
`answer_value` is still recorded in every row. Only single-line, single-value answers are
normalised; multi-line and compound (`"(a) ... (b) ..."`) answers are left untouched.
`--disable-normalization` uses the raw `answer_value`, for an A/B check.

Per-row timeout (`--row-timeout-seconds`, default 600). During a full-pool run, id=23 appeared to
hang for over 30 minutes. That turned out to be a monitoring artefact (it took 15.4 s; the first
71 rows took 8.5-48.1 s), but the concern stands: nothing stopped a pathological row, such as a
degenerate generation on a truncated question (id=23 is truncated, see Issue 291), from using an
unbounded share of a run of about 9 hours unnoticed. Every `generate()` and `generate_multiple()`
call has a `max_new_tokens` cap, but a slow worst case (thermal throttling, a long prompt, several
chained calls near their caps) can still take minutes. Without a ceiling, "slow but fine" cannot
be told apart from "stuck" without watching `nvidia-smi` by hand, which does not work for a long
unattended run.

The timeout is a `ThreadPoolExecutor(max_workers=1)` watchdog around each row's
`run_full_gate_pipeline()` call and the forced Tier 1 `generate_hint()` call. A timeout stops the
run rather than skipping the row. Python cannot kill a thread blocked in a C extension or CUDA
call, so the timed-out call keeps running. If the loop moved on, the next row's `generate()` would
run concurrently on the same module-level `_model` and `_tokenizer` in `llm_service.py`, and
`model.generate()` is not documented as safe for two threads sharing one instance; that risks a
CUDA error or corrupted output for both calls. So on a timeout: rows already written are safe
(each row is flushed as it is written), the timed-out row is logged to a `*.timeouts.json`
sidecar, and the process exits non-zero. Re-running with the same `--out` skips every completed
`(question_id, tier)` and retries the row that timed out.

Hint generation, per surviving candidate:
  * `gate.run_full_gate_pipeline(question_text, answer_value_gate, has_diagram,
    worked_solution_text)`, the live pipeline (self-consistency or SymPy, then method alignment,
    then the hint). One queue row is written for the hint it produces (Tier 1 if the gate capped
    it, Tier 2 if the gate passed).
  * If that hint is Tier 2 or higher, a forced Tier 1 restatement row is also written, so the
    queue covers both system-prompt shapes (Issue 246). A grounded Tier 2 hint is never written
    for a row the gate did not pass, since that is the ungrounded training pair Issues 246 and 47
    warn about.

Diagram rows: a Tier 2 or 3 hint for a `has_diagram=1` row can refer to figure content a text-only
model never saw, which a reviewer reading only the hint text cannot catch. Every row with
`has_diagram=1` and `tier >= 2` therefore carries `source_page_image` (the repository-relative
path of the cached page PNG, `data/extracted/pages/{pdf_stem}/{source_page_index}.png`) and
`source_page_image_exists` (checked on disk). Tier 1 rows and `has_diagram=0` rows never carry it,
since a Tier 1 restatement never refers to solution or figure content.

Output: JSONL, one queue row per line, under `data/extracted/slice6_step0c/` (not published):
  {"question_id", "tier", "system_prompt", "question_text", "bootstrapped_hint",
   "reviewed": false, "reviewed_hint": null, "review_notes": null,
   provenance: "gate_passed", "gate_tier_allowed", "gate_reason", "question_type",
       "grounded_in", "self_consistency_summary", "answer_value", "answer_value_gate",
       "answer_value_normalization_rules", "worked_solution_text", "has_diagram", "source_paper",
       "answer_value_class", "bootstrap_generated_at",
   plus "source_page_image" and "source_page_image_exists" (diagram rows of Tier 2+ only)}

Resumable: re-running with the same `--out` skips any (question_id, tier) already present.
Re-running on a complete file writes 0 new rows.

GPU checks (Issue 248): prints `nvidia-smi` output before loading anything, and refuses to start
if less than 3,500 MiB is free (Phi-4-mini in NF4 needs about 3 GB) or if another large ML process
looks resident. Only one large model runs at a time; this loads only Phi-4-mini, through the usual
lazy `llm_service.get_llm()` path. `--gpu-check-every N` (default 50) re-prints free VRAM every N
questions, so a leaking process is caught mid-run, and the run stops if free VRAM falls below
1,000 MiB.

Usage:
    # Small trial slice first; do not scale up without sign-off:
    backend/.venv/Scripts/python.exe scripts/training/build_hint_review_queue.py --limit 25
    # Diagram-free rows only:
    backend/.venv/Scripts/python.exe scripts/training/build_hint_review_queue.py --limit 25 \
        --diagram-free-only
    # Specific ids:
    backend/.venv/Scripts/python.exe scripts/training/build_hint_review_queue.py --ids 1455,1602,2931
"""
